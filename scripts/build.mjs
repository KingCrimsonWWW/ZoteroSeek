/**
 * ZoteroSeek 构建脚本。
 *
 * 产物（都落在 plugin/ 里，是 DSH 安装目录，会被提交）：
 *   plugin/index.js   Host 半边：ESM，`export function apply(ctx, config)`
 *   plugin/client.js  Client 半边：浏览器模块加载器格式（factory(require)）
 *
 * 用法：node scripts/build.mjs [--watch]
 */
import { build, context } from 'esbuild'
import { readFile, writeFile, mkdir } from 'node:fs/promises'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = dirname(fileURLToPath(new URL('.', import.meta.url)))
const pkg = JSON.parse(await readFile(join(root, 'package.json'), 'utf8'))
const pluginDir = join(root, 'plugin')
await mkdir(join(pluginDir, 'docs'), { recursive: true })

const bundlePkg = JSON.parse(await readFile(join(pluginDir, 'package.json'), 'utf8'))
const PLUGIN_ID = bundlePkg.name

/** 浏览器里由 DSH 模块表提供的模块：不打进 bundle，留给 factory(require)。 */
const CLIENT_EXTERNAL = [
  'react',
  'react-dom',
  'react-dom/client',
  'react/jsx-runtime',
  'react/jsx-dev-runtime',
]

const watch = process.argv.includes('--watch')

/** Host 半边：单个 ESM 文件，不依赖 node_modules。 */
const hostOptions = {
  entryPoints: [join(root, 'src/host/index.ts')],
  outfile: join(pluginDir, 'index.js'),
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  sourcemap: false,
  logLevel: 'info',
  banner: {
    js: `/** ${pkg.name} host half — generated by scripts/build.mjs, do not edit. */`,
  },
}

/**
 * Client 半边：先打成 CJS（react 等留作 external），再包进 DSH 的
 * `window.__ModuleLoader__.load({ id, factory(require) })` 外壳。
 * 这样 factory 里 `require('react')` 由页面模块表解析，不会重复打包 React。
 */
const clientOptions = {
  entryPoints: [join(root, 'src/client/index.tsx')],
  outfile: join(root, 'dist/client.cjs'),
  bundle: true,
  platform: 'browser',
  format: 'cjs',
  target: 'es2022',
  external: CLIENT_EXTERNAL,
  jsx: 'automatic',
  loader: { '.css': 'text' },
  sourcemap: false,
  logLevel: 'info',
}

async function wrapClient() {
  const code = await readFile(join(root, 'dist/client.cjs'), 'utf8')
  const wrapped = `/** ${pkg.name} client half — generated by scripts/build.mjs, do not edit. */
window.__ModuleLoader__.load({
  id: ${JSON.stringify(PLUGIN_ID)},
  factory(require) {
    const module = { exports: {} };
    const exports = module.exports;
${code}
    return module.exports.default ?? module.exports;
  },
});
`
  await writeFile(join(pluginDir, 'client.js'), wrapped, 'utf8')
  console.log(`[build] plugin/client.js  ${(wrapped.length / 1024).toFixed(1)} KiB`)
}

if (watch) {
  const hostCtx = await context({
    ...hostOptions,
    plugins: [
      {
        name: 'client-sidecar',
        setup(b) {
          b.onEnd(async (result) => {
            if (result.errors.length === 0) {
              try {
                await wrapClient()
              } catch (error) {
                console.error('[build] client wrap failed:', error)
              }
            }
          })
        },
      },
    ],
  })
  const clientCtx = await context(clientOptions)
  await Promise.all([hostCtx.watch(), clientCtx.watch()])
  console.log('[build] watching…')
} else {
  await build(hostOptions)
  await build(clientOptions)
  await wrapClient()
  const host = await readFile(join(pluginDir, 'index.js'), 'utf8')
  console.log(`[build] plugin/index.js   ${(host.length / 1024).toFixed(1)} KiB`)
  console.log('[build] ok')
}
